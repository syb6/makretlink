<?php

namespace App\Http\Middleware;

use Closure;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Validation\ValidationException;
use Symfony\Component\HttpFoundation\Response;

/**
 * Lets the Angular SPA reuse the existing Blade controllers for mutations.
 *
 * Workflow controllers (cart, checkout, orders, admin CRUD) answer as
 * redirects carrying flashed messages — perfect for Blade pages, useless for
 * an SPA. This bridge intercepts those RedirectResponses and returns them as
 * JSON: `{ ok, flash, redirect, validation }` — the flash keys the layout
 * partial would have shown (success / error / info) plus the redirect target
 * so the SPA decides where to navigate.
 */
class JsonFlashBridge
{
    public function handle(Request $request, Closure $next): Response
    {
        /** @var Response $response */
        $response = $next($request);

        if (! $this->wantsJsonBridge($request, $response)) {
            return $response;
        }

        // Validation failures already come back as 422 JSON when the client
        // accepts JSON — pass them untouched.
        if ($response->isServerError()) {
            return $response;
        }

        $flash = [];
        foreach (['success', 'error', 'info', 'reset-status', 'reset-url', 'reset-expiry', 'reset-newest'] as $key) {
            if (session()->has($key)) {
                $flash[$key] = session($key);
            }
        }

        $errors = session('errors');
        $validation = $errors ? (array) $errors->messages() : [];
        $status = $validation === [] ? 200 : 422;

        $payload = [
            'ok' => ! (isset($flash['error']) && $flash['error'] !== '') && $validation === [],
            'flash' => $flash,
            'validation' => $validation,
            // Laravel wrote the target as an absolute URL; the SPA only wants a path.
            'redirect' => $this->pathOf($response instanceof RedirectResponse ? $response->getTargetUrl() : '/'),
            'status' => $status,
        ];

        $json = new JsonResponse($payload, $status);

        // The session may have been regenerated by the wrapped controller
        // (login/logout): keep its Set-Cookie headers, otherwise the SPA
        // would keep the stale session cookie and appear logged out.
        foreach ($response->headers->getCookies() as $cookie) {
            $json->headers->setCookie($cookie);
        }

        return $json;
    }

    private function wantsJsonBridge(Request $request, Response $response): bool
    {
        if (! $request->expectsJson()) {
            return false;
        }

        // Redirects always carry messages we must translate.
        if ($response instanceof RedirectResponse) {
            return true;
        }

        // A 403/404 etc. as JSON is fine as-is (handled by the exception handler).
        return false;
    }

    private function pathOf(string $url): string
    {
        $path = parse_url($url, PHP_URL_PATH) ?: '/';

        return $path === '' ? '/' : $path;
    }
}
