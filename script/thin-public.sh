#!/usr/bin/env bash
set -euo pipefail

# Thin out the repo for deployment by stopping git from tracking
# heavy build artifacts and static assets that are regenerated or
# can be fetched from cdn in production. Keeps only runtime-critical
# public assets tracked.

set -x
git ls-files --stage public/css/app.min.css public/js/app.min.js public/js/marketlink.js public/js/marketlink.min.js public/js/chatbot.js public/js/chatbot.min.js \
  public/vendor/bootstrap/css/bootstrap.min.css \
  public/vendor/bootstrap/js/bootstrap.bundle.min.js \
  public/vendor/bootstrap-icons/css/bootstrap-icons.min.css \
  public/vendor/leaflet/leaflet.js public/vendor/leaflet/leaflet.css \
  public/images/hero-bg.webp public/images/hero-bg-800.webp public/images/hero-basket.webp \
  | awk '{print $4}' \
  | xargs -r git rm -f --cached

# Keep the spa entry point (and its license file) tracked so the SPA
# route / and deep links keep working; everything else under public/spa/
# is regenerated by the angular build step.
